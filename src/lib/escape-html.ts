// Escapes user-supplied text before it is placed inside email HTML, so a
// registrant can't inject links or markup into emails sent from our domain.
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
